"""Generate the Protobuf definitions for AAS meta-models."""

import argparse
import os
import pathlib
import re
import sys

import aas_core_codegen.main
import aas_core_meta.v3

# NOTE (aaronzi, 2026-11-05):
# aas-core-codegen does not emit any copyright or license information, so we
# prepend the header to the generated definitions ourselves. Otherwise, the
# headers would be lost on every re-generation.
#
# REUSE-IgnoreStart
_LICENSE_HEADER = """\
// SPDX-FileCopyrightText: 2024 aas-core-protobuf AUTHORS
//
// SPDX-License-Identifier: MIT

"""
# REUSE-IgnoreEnd

_LEADING_SPDX_COMMENTS_RE = re.compile(r"\A(?://\s*(?:SPDX-[A-Za-z-]+:.*)?\n|\n)*")

_GENERATED_MARKER = "This code has been automatically generated by aas-core-codegen."


def _prepend_license_header(text: str) -> str:
    """Replace any leading SPDX comment block in ``text`` with our license header."""
    return _LICENSE_HEADER + _LEADING_SPDX_COMMENTS_RE.sub("", text, count=1)


def _add_license_headers(output_dir: pathlib.Path) -> None:
    """Prepend the license header to the definitions generated by aas-core-codegen."""
    for path in sorted(output_dir.glob("*.proto")):
        text = path.read_text(encoding="utf-8")
        if _GENERATED_MARKER not in text:
            continue

        path.write_text(_prepend_license_header(text), encoding="utf-8")


def module_basename(name: str) -> str:
    """
    Extract the last name in a qualified module name.

    >>> module_basename("aas_core_meta.v3")
    'v3'
    """
    return name.split(".")[-1]


def main() -> int:
    """Execute the main routine."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()

    this_path = pathlib.Path(os.path.realpath(__file__))

    for meta_model in [aas_core_meta.v3]:
        assert meta_model.__file__ is not None
        model_path = pathlib.Path(meta_model.__file__)
        meta_model_basename = module_basename(meta_model.__name__)

        print(f"Generating the definitions for meta-model: {meta_model_basename}")

        codegen_params = aas_core_codegen.main.Parameters(
            model_path=model_path,
            target=aas_core_codegen.main.Target.PROTOBUF,
            snippets_dir=this_path.parent.parent / "snippets" / meta_model_basename,
            output_dir=this_path.parent.parent.parent / meta_model_basename,
        )

        aas_core_codegen.main.execute(
            params=codegen_params, stdout=sys.stdout, stderr=sys.stderr
        )

        _add_license_headers(codegen_params.output_dir)

    return 0


if __name__ == "__main__":
    sys.exit(main())
